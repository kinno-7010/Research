"""
gcs_overlay.py
--------------
Overlay a GCS wireframe (generated by gcs_geometry) on the user's existing
composite coronagraph plot created by `create_single_diff_image(ax, time_str)`.

The overlay uses SunPy's coordinate frames to project 3D HGS points to
Helioprojective coordinates *with the LASCO map's observer*, then converts
arcsec -> Rsun -> pixels using the LASCO scale embedded in the user's composite.
"""
from dataclasses import dataclass
from typing import Dict, List, Tuple, Optional
import sys
import numpy as np
import matplotlib.pyplot as plt
from astropy import units as u
from astropy.coordinates import SkyCoord
from astropy.time import Time

# We import only our minimal geometry helper
from .gcs_geometry import GCSParams, sample_gcs_wireframe_points

# SunPy frames imports are inside functions to avoid import-time issues if SunPy is not present.
def _to_hpc_arcsec_for_lasco(lasco_map, pts_hgs: np.ndarray, obstime: Time):
    """
    Convert Nx3 array of HGS Cartesian (Rsun) points to HPC arcsec for the LASCO observer.
    """
    import numpy as np
    from sunpy.coordinates import frames

    X, Y, Z = pts_hgs[:,0], pts_hgs[:,1], pts_hgs[:,2]
    r = np.sqrt(X*X + Y*Y + Z*Z)

    # Convert to spherical (lon, lat) in HGS
    lon = np.arctan2(Y, X) * u.rad
    lat = np.arcsin(Z / np.where(r>0, r, 1.0)) * u.rad
    radius = r * u.R_sun

    hgs = SkyCoord(lon=lon, lat=lat, radius=radius,
                   frame=frames.HeliographicStonyhurst,
                   obstime=obstime)

    # Transform to HPC using LASCO map's observer and obstime
    hpc = hgs.transform_to(
        frames.Helioprojective(
            observer=lasco_map.observer_coordinate, 
            obstime=lasco_map.date
        )
    )
    # hpc.Tx, hpc.Ty are in arcsec
    x_arcsec = hpc.Tx.to_value(u.arcsec)
    y_arcsec = hpc.Ty.to_value(u.arcsec)
    return x_arcsec, y_arcsec

def _arcsec_to_pixels_using_lasco_scale(x_arcsec: np.ndarray, y_arcsec: np.ndarray, lasco_map, p_lasco: Dict):
    """
    Convert HPC arcsec -> Rsun fraction (using LASCO's apparent solar radius) -> pixels
    relative to composite extent centered at (0,0).
    """
    rsun_arcsec = lasco_map.rsun_obs.to_value(u.arcsec)
    xr = x_arcsec / rsun_arcsec   # in Rsun
    yr = y_arcsec / rsun_arcsec
    scale = p_lasco['px_per_rsun']  # pixels per Rsun in the composite
    xp = xr * scale
    yp = yr * scale
    return xp, yp

def overlay_gcs_wireframe_on_axes(
    ax,
    lasco_map,
    p_lasco: Dict,
    gcs_params: GCSParams,
    obstime_str: str,
    n_parallels: int = 8,
    n_meridians: int = 12,
    color: str = 'white',
    lw: float = 1.0,
    alpha: float = 0.8,
    include_legs: bool = True
) -> Dict[str, List[np.ndarray]]:
    """
    Core overlay function to draw the wireframe given LASCO map + scale (from the composite).
    Returns the pixel polylines used (useful for debugging or saving).
    """
    # Sample 3D HGS points (Rsun)
    obstime = Time(obstime_str)

    wire = sample_gcs_wireframe_points(
        gcs_params,
        obstime=obstime,
        n_parallels=n_parallels,
        n_meridians=n_meridians,
        include_legs=include_legs,
    )

    legend_label = gcs_params.legend_label()
    legend_assigned = False

    polylines_px = {"parallels": [], "meridians": [], "legs": []}

    # Helper to project and draw
    def _project_and_draw(curves: List[np.ndarray], zorder:int):
        nonlocal legend_assigned
        out = []
        for pts in curves:
            xa, ya = _to_hpc_arcsec_for_lasco(lasco_map, pts, obstime)
            xp, yp = _arcsec_to_pixels_using_lasco_scale(xa, ya, lasco_map, p_lasco)
            label = legend_label if (legend_label and not legend_assigned) else None
            line_handles = ax.plot(xp, yp, color=color, lw=lw, alpha=alpha, zorder=zorder, label=label)
            if label and line_handles:
                legend_assigned = True
            out.append(np.column_stack([xp, yp]))
        return out

    polylines_px["parallels"] = _project_and_draw(wire["parallels"], zorder=5)
    polylines_px["meridians"] = _project_and_draw(wire["meridians"], zorder=5)
    if include_legs and len(wire["legs"])>0:
        polylines_px["legs"] = _project_and_draw(wire["legs"], zorder=4)

    if legend_assigned:
        handles, labels = ax.get_legend_handles_labels()
        if labels:
            ax.legend(handles, labels)

    return polylines_px

def overlay_gcs_on_composite(
    ax,
    target_time_str: str,
    gcs_params: GCSParams,
    n_parallels: int = 8,
    n_meridians: int = 12,
    color: str = 'white',
    lw: float = 1.0,
    alpha: float = 0.8,
    include_legs: bool = True
) -> dict:
    """
    Convenience function:
      - Calls user's create_single_diff_image(ax, target_time_str)
      - Overlays the GCS wireframe using LASCO geometry from that composite
      - Returns a dict with:
          {
            'base': <return of create_single_diff_image>,
            'polylines': <pixel space polylines dict>
          }
    """
    # Import lazily to avoid pulling user config on import
    from integrated_analysis import create_single_diff_image

    # Patch Horizons lookup to tolerate offline execution (no network access)
    if not hasattr(overlay_gcs_on_composite, "_horizons_patched"):
        from sunpy.coordinates import ephemeris
        from sunpy.coordinates import frames
        from astropy.coordinates import SkyCoord
        from astropy import units as u
        from requests.exceptions import RequestException

        original_get_horizons = ephemeris.get_horizons_coord

        def _get_horizons_with_fallback(target, obstime, *args, **kwargs):
            try:
                return original_get_horizons(target, obstime, *args, **kwargs)
            except RequestException:
                pass
            except Exception as exc:  # pragma: no cover - protective fallback
                if "Name or service not known" not in str(exc):
                    raise
            target_upper = str(target).upper()
            if target_upper == 'SOHO':
                return SkyCoord(
                    lon=0.0 * u.deg,
                    lat=0.0 * u.deg,
                    radius=1.0 * u.AU,
                    frame=frames.HeliographicStonyhurst,
                    obstime=obstime,
                    observer='earth',
                )
            return original_get_horizons(target, obstime, *args, **kwargs)

        ephemeris.get_horizons_coord = _get_horizons_with_fallback
        module_integrated = sys.modules.get('integrated_analysis')
        if module_integrated is not None:
            module_integrated.get_horizons_coord = _get_horizons_with_fallback
        overlay_gcs_on_composite._horizons_patched = True

    base_info = create_single_diff_image(ax, target_time_str)
    lasco_map = base_info['lasco_map']
    p_lasco   = base_info['params_lasco']

    polylines = overlay_gcs_wireframe_on_axes(
        ax, lasco_map, p_lasco, gcs_params, obstime_str=target_time_str,
        n_parallels=n_parallels, n_meridians=n_meridians,
        color=color, lw=lw, alpha=alpha, include_legs=include_legs
    )
    return {'base': base_info, 'polylines': polylines}
